// Use an isolated seeded development database: this script retains synthetic review/history records.
async page => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const base = new URL(page.url()).origin;
  const name = 'Årgång · Etapp 2 · ' + Date.now();
  const errors = [];
  const external = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.context().route('**/*', route => {
    const url = route.request().url();
    if (url.startsWith('http') && new URL(url).origin !== base) {
      external.push(url);
      return route.abort();
    }
    return route.continue();
  });
  const overflow = async () => {
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Phone layout overflow');
  };
  await page.setViewportSize({width: 390, height: 844});
  await page.goto(base + '/');
  if (await page.locator('#id_username').count()) {
    await page.locator('#id_username').fill('demo');
    await page.locator('#id_password').fill('demo');
    await page.getByRole('button', {name: 'Logga in', exact: true}).click();
  }
  await page.goto(base + '/wines/add/');
  await page.locator('#id_name').fill(name);
  await page.locator('#id_producer').fill('Östra testslottet');
  await page.locator('#id_country').fill('Frankrike');
  await page.locator('#id_grapes_text').fill('Pinot noir, Gamay');
  await page.locator('#id_notes').fill('Rad ett\nRad två <script>');
  await page.locator('#id_photo').setInputFiles({name: 'bad.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('not an image')});
  await page.getByRole('button', {name: 'Spara', exact: true}).click();
  assert(await page.locator('.errorlist').count() > 0, 'Invalid photo accepted');
  assert(await page.locator('#id_name').inputValue() === name, 'Image failure lost profile input');
  const photo = await page.evaluate(() => {
    const canvas = document.createElement('canvas');
    canvas.width = 240; canvas.height = 400;
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = '#f6eddc'; ctx.fillRect(0, 0, 240, 400);
    ctx.fillStyle = '#314939'; ctx.fillRect(95, 100, 50, 250); ctx.fillRect(110, 40, 20, 70);
    ctx.fillStyle = '#6c283b'; ctx.fillRect(109, 40, 22, 25);
    ctx.fillStyle = '#fffdf9'; ctx.fillRect(96, 205, 48, 70);
    return canvas.toDataURL('image/png').split(',')[1];
  });
  await page.locator('#id_photo').setInputFiles({name: 'phone.png', mimeType: 'image/png', buffer: Buffer.from(photo, 'base64')});
  await page.getByRole('button', {name: 'Spara', exact: true}).click();
  await page.locator('#q').fill(name.toUpperCase());
  await page.getByRole('button', {name: 'Sök', exact: true}).click();
  await page.waitForURL(url => url.searchParams.get('q') === name.toUpperCase());
  const card = page.locator('.wine-card').filter({hasText: name});
  assert(await page.locator('.wine-card').count() === 1, 'Unicode search did not isolate saved profile');
  assert(await card.locator('img').evaluate(img => img.complete && img.naturalWidth > 0), 'Private photo failed to load');
  await overflow();
  await card.getByRole('link', {name, exact: true}).click();
  const detailUrl = page.url();
  const wineId = new URL(detailUrl).pathname.split('/')[2];
  assert(await page.getByText('Inga tillgängliga flaskor i det här urvalet.', {exact: true}).count() === 1, 'Profile creation added bottles');
  await page.getByRole('link', {name: 'Lägg till recension', exact: true}).click();
  await page.locator('#id_score').selectOption('3.5');
  await page.locator('#id_date').fill('2026-11-10');
  await page.locator('#id_notes').fill('Syra och röda bär\nLång eftersmak');
  await page.getByRole('button', {name: 'Spara', exact: true}).click();
  assert(await page.locator('.reviews').getByText('3,5/5 ★', {exact: true}).count() === 1, 'Half-star review not displayed');
  await page.locator('a.back').click();
  assert(new URL(page.url()).searchParams.get('q') === name.toUpperCase(), 'Catalogue return lost search');

  await page.goto(base + '/settings/');
  const shelf = 'Etapp 2 hylla ' + Date.now();
  await page.locator('#id_name').fill(shelf);
  await page.locator('#id_name').locator('xpath=ancestor::form').getByRole('button', {name: 'Spara', exact: true}).click();
  const locationRow = page.locator('.location-list li').filter({hasText: shelf});
  const manageUrl = await locationRow.getByRole('link', {name: 'Hantera plats', exact: true}).getAttribute('href');
  const locationId = manageUrl.split('/')[3];
  await page.locator('#id_store_id').fill('0012');
  await page.locator('#id_store_name').fill('Syntetisk butik');
  await page.locator('#id_store_id').locator('xpath=ancestor::form').getByRole('button', {name: 'Spara', exact: true}).click();
  assert(await page.locator('#id_store_id').inputValue() === '0012', 'Store leading zeroes lost');
  await page.goto(base + '/bottles/add/');
  await page.locator('#id_wine').selectOption(wineId);
  await page.locator('#id_location').selectOption(locationId);
  await page.locator('#id_quantity').fill('2');
  await page.locator('#id_purchase_price').fill('0');
  await page.getByRole('button', {name: 'Spara', exact: true}).click();
  await page.locator('#q').fill(name.toUpperCase());
  await page.locator('#location').selectOption(locationId);
  await page.getByRole('button', {name: 'Sök', exact: true}).click();
  await page.waitForURL(url => url.searchParams.get('q') === name.toUpperCase() && url.searchParams.get('location') === locationId);
  assert(await card.getByText('3,5/5 ★', {exact: false}).count() === 1, 'Card latest score missing');
  await card.getByRole('link', {name, exact: true}).click();
  await page.getByRole('link', {name: /Redigera flaska/}).first().click();
  await page.locator('#id_location').selectOption('');
  await page.getByRole('button', {name: 'Spara', exact: true}).click();
  assert(await page.locator('.bottle-group').count() === 1, 'Move did not update scoped group');
  await page.getByRole('link', {name: /Ta bort flaska/}).first().click();
  await page.locator('#id_reason').selectOption('gift');
  await page.getByRole('button', {name: 'Spara', exact: true}).click();
  assert(await page.locator('.bottle-group').count() === 0, 'Gift remained available in selected scope');

  await page.goto(base + '/wines/' + wineId + '/retire/');
  await page.getByRole('button', {name: 'Bekräfta', exact: true}).click();
  await page.goto(base + '/?q=' + encodeURIComponent(name));
  assert(await card.count() === 1, 'Archive hid available stock');
  await page.goto(base + manageUrl);
  await page.locator('#id_action').selectOption('archive');
  await page.getByRole('button', {name: 'Spara', exact: true}).click();
  await page.goto(base + manageUrl);
  await page.locator('#id_action').selectOption('restore');
  await page.getByRole('button', {name: 'Spara', exact: true}).click();
  await page.goto(base + '/settings/');
  await overflow();
  await page.locator('#export-wines').getByRole('button', {name: 'Skapa', exact: true}).click();
  await page.locator('#markdown-wines').waitFor();
  const allWines = await page.locator('#markdown-wines').inputValue();
  assert(allWines.includes(name) && allWines.includes('[Archived]') && allWines.includes('3.5/5') && allWines.includes('Rad två <script>'), 'Catalogue Markdown omitted notes/reviews/archive');
  await page.locator('#export-location').selectOption(locationId);
  await page.locator('#export-bottles').getByRole('button', {name: 'Skapa', exact: true}).click();
  await page.locator('#markdown-bottles').waitFor();
  assert((await page.locator('#markdown-bottles').inputValue()).includes('0 bottles available.'), 'Empty location export incorrect');
  assert(await page.locator('#markdown-wines').inputValue() === allWines, 'Bottle generation replaced catalogue preview');
  await page.locator('#export-location').selectOption('unassigned');
  await page.locator('#export-bottles').getByRole('button', {name: 'Skapa', exact: true}).click();
  await page.waitForFunction(() => document.querySelector('#markdown-bottles')?.value.includes('Location scope: Unassigned'));
  assert((await page.locator('#markdown-bottles').inputValue()).includes(name), 'Unassigned export omitted available archived wine');
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.locator('#export-wines').getByRole('button', {name: 'Kopiera', exact: true}).click();
  await page.locator('#export-wines [data-copy-status]').getByText('Kopierat.', {exact: true}).waitFor();
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  assert(copied.replaceAll('\r\n', '\n') === allWines, 'Copy changed Markdown text');
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', {configurable: true, value: {writeText: async () => { throw new Error('unavailable'); }}}));
  await page.locator('#export-bottles').getByRole('button', {name: 'Kopiera', exact: true}).click();
  await page.getByText('Markera och kopiera texten manuellt.', {exact: true}).waitFor();
  await overflow();
  await page.screenshot({path: 'test-results/settings-stage2-mobile.png', fullPage: true});

  await page.context().clearCookies({name: 'sessionid'});
  await page.locator('#export-wines').getByRole('button', {name: 'Skapa', exact: true}).click();
  await page.getByRole('heading', {name: 'Logga in igen'}).waitFor();
  await page.getByRole('link', {name: 'Logga in', exact: true}).click();
  await page.locator('#id_username').fill('demo');
  await page.locator('#id_password').fill('demo');
  await page.getByRole('button', {name: 'Logga in', exact: true}).click();
  assert(new URL(page.url()).pathname === '/settings/', 'Expired export returned to a POST-only route');
  await page.goto(base + '/timeline/?wine=' + wineId);
  assert(await page.getByRole('heading', {name: /Recension/}).count() === 1, 'Review missing in filtered timeline');
  assert(await page.getByRole('heading', {name: /Gåva/}).count() === 1, 'Gift missing in filtered timeline');
  assert(await page.getByRole('heading', {name: /Flyttade flaska/}).count() === 1, 'Move missing in filtered timeline');
  await overflow();
  await page.setViewportSize({width: 320, height: 740});
  await overflow();
  await page.goto(base + '/wines/?archived=1&q=' + encodeURIComponent(name));
  await card.getByRole('link', {name: 'Återställ', exact: true}).click();
  await page.getByRole('button', {name: 'Bekräfta', exact: true}).click();
  await page.goto(base + '/bottles/add/');
  assert(await page.locator('#id_wine option[value="' + wineId + '"]').count() === 1, 'Restored profile missing from add selector');
  await page.goto(base + '/?q=' + encodeURIComponent(name));
  await card.getByRole('button', {name: 'Drick', exact: true}).click();
  assert(await card.count() === 0, 'Last consumed bottle remained in Cellar');
  assert(external.length === 0, 'Local workflows attempted external requests: ' + external.join(', '));
  assert(errors.length === 0, 'Browser JavaScript errors: ' + errors.join(', '));
  return 'Stage 2 phone smoke passed: image validation/upload, Unicode search, dated half-star review, context, move/gift, archive/restore, store ID, independent Markdown scopes/copy/fallback, expired HTMX session, timeline, last-bottle consumption; no external requests.';
}
